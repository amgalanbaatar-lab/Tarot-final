// Utilities for Numerology Calculation
export function reduceToSingleOrMaster(num: number): number {
  if (num === 11 || num === 22 || num === 33) return num;
  while (num > 9) {
    if (num === 11 || num === 22 || num === 33) return num;
    num = num
      .toString()
      .split('')
      .reduce((acc, digit) => acc + parseInt(digit, 10), 0);
  }
  return num;
}

export function calculateLifePath(birthDateStr: string): number {
  const parts = birthDateStr.split(/[-/.]/).map(p => parseInt(p, 10));
  if (parts.length !== 3 || parts.some(isNaN)) {
    return 7;
  }
  const [year, month, day] = parts[0] > 1000 ? [parts[0], parts[1], parts[2]] : [parts[2], parts[1], parts[0]];

  const rMonth = reduceToSingleOrMaster(month);
  const rDay = reduceToSingleOrMaster(day);
  const rYear = reduceToSingleOrMaster(year);

  return reduceToSingleOrMaster(rMonth + rDay + rYear);
}

export function calculateBirthdayNumber(birthDateStr: string): number {
  const parts = birthDateStr.split(/[-/.]/).map(p => parseInt(p, 10));
  if (parts.length !== 3 || parts.some(isNaN)) return 7;
  const day = parts[0] > 1000 ? parts[2] : parts[0];
  return reduceToSingleOrMaster(day);
}

export function calculatePersonalYear(birthDateStr: string, currentYear = 2026): number {
  const parts = birthDateStr.split(/[-/.]/).map(p => parseInt(p, 10));
  if (parts.length !== 3 || parts.some(isNaN)) return 9;
  const month = parts[1];
  const day = parts[0] > 1000 ? parts[2] : parts[0];

  const rMonth = reduceToSingleOrMaster(month);
  const rDay = reduceToSingleOrMaster(day);
  const rYear = reduceToSingleOrMaster(currentYear);

  return reduceToSingleOrMaster(rMonth + rDay + rYear);
}

